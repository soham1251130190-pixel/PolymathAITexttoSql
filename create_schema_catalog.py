import sqlite3
import pandas as pd
from pathlib import Path

# ============================================================
# PATHS
# ============================================================

DB_PATH = Path("financial_datasets/database/financial_data.db")
SCHEMA_DIR = Path("financial_datasets/schema")
OUTPUT_PATH = SCHEMA_DIR / "financial_schema_catalog.csv"

SCHEMA_DIR.mkdir(parents=True, exist_ok=True)


# ============================================================
# CONNECT TO DATABASE
# ============================================================

conn = sqlite3.connect(DB_PATH)


# ============================================================
# READ FINANCIAL CONCEPTS
# ============================================================

query = """
SELECT
    concept_id,
    concept_name,
    xbrl_tag,
    statement_type
FROM financial_concepts
ORDER BY statement_type, concept_name
"""

concepts = pd.read_sql_query(query, conn)


# ============================================================
# ADD FINANCIAL DESCRIPTIONS
# ============================================================

descriptions = {

    "Revenue":
        "Revenue generated by the company during the financial period.",

    "Cost of Goods Sold":
        "Costs associated with goods and services sold by the company during the financial period.",

    "Gross Profit":
        "Revenue remaining after subtracting the cost of goods sold.",

    "Operating Income":
        "Income generated from operations after operating expenses.",

    "Net Income":
        "Profit or loss remaining after all applicable expenses, including taxes and other items.",

    "Total Assets":
        "Total assets held by the company at the reporting date.",

    "Current Assets":
        "Assets expected to be converted to cash, sold, or used within the current operating cycle or generally within one year.",

    "Total Liabilities":
        "Total obligations and liabilities of the company at the reporting date.",

    "Current Liabilities":
        "Liabilities expected to be settled within the current operating cycle or generally within one year.",

    "Stockholders Equity":
        "Equity attributable to the company's stockholders at the reporting date.",

    "Cash and Cash Equivalents":
        "Cash and highly liquid cash-equivalent assets held by the company at the reporting date.",

    "Inventory":
        "Inventory held by the company at the reporting date.",

    "Accounts Receivable":
        "Amounts owed to the company by customers or other parties at the reporting date.",

    "Property Plant and Equipment":
        "Long-term physical assets used in the company's operations.",

    "Operating Cash Flow":
        "Net cash provided by or used in the company's operating activities during the financial period.",

    "Investing Cash Flow":
        "Net cash provided by or used in the company's investing activities during the financial period.",

    "Financing Cash Flow":
        "Net cash provided by or used in the company's financing activities during the financial period.",

    "Capital Expenditure":
        "Cash payments made to acquire property, plant, and equipment during the financial period."
}


concepts["description"] = concepts["concept_name"].map(descriptions)


# ============================================================
# DETERMINE PERIOD TYPE
# ============================================================

instant_concepts = {
    "Total Assets",
    "Current Assets",
    "Total Liabilities",
    "Current Liabilities",
    "Stockholders Equity",
    "Cash and Cash Equivalents",
    "Inventory",
    "Accounts Receivable",
    "Property Plant and Equipment"
}

concepts["period_type"] = concepts["concept_name"].apply(
    lambda x: "instant" if x in instant_concepts else "duration"
)


# ============================================================
# DETERMINE UNIT
# ============================================================

concepts["expected_unit"] = "USD"


# ============================================================
# DETERMINE QUERY TYPE
# ============================================================

concepts["query_type"] = concepts["concept_name"].apply(
    lambda x: (
        "point_in_time"
        if x in instant_concepts
        else "period_value"
    )
)


# ============================================================
# ADD SEARCH TERMS
# ============================================================

search_terms = {

    "Revenue":
        "revenue sales income sales revenue",

    "Cost of Goods Sold":
        "cost of goods sold COGS cost of sales",

    "Gross Profit":
        "gross profit",

    "Operating Income":
        "operating income operating profit",

    "Net Income":
        "net income net earnings profit",

    "Total Assets":
        "total assets assets",

    "Current Assets":
        "current assets",

    "Total Liabilities":
        "total liabilities liabilities",

    "Current Liabilities":
        "current liabilities",

    "Stockholders Equity":
        "stockholders equity shareholders equity equity",

    "Cash and Cash Equivalents":
        "cash cash equivalents cash and equivalents",

    "Inventory":
        "inventory stock",

    "Accounts Receivable":
        "accounts receivable receivables",

    "Property Plant and Equipment":
        "property plant equipment PP&E fixed assets",

    "Operating Cash Flow":
        "operating cash flow cash from operations",

    "Investing Cash Flow":
        "investing cash flow cash from investing",

    "Financing Cash Flow":
        "financing cash flow cash from financing",

    "Capital Expenditure":
        "capital expenditure capex property plant equipment purchases"
}

concepts["search_terms"] = concepts["concept_name"].map(search_terms)


# ============================================================
# REORDER COLUMNS
# ============================================================

concepts = concepts[
    [
        "concept_id",
        "concept_name",
        "xbrl_tag",
        "statement_type",
        "description",
        "period_type",
        "expected_unit",
        "query_type",
        "search_terms"
    ]
]


# ============================================================
# VALIDATION
# ============================================================

missing_descriptions = concepts[
    concepts["description"].isna()
]

if len(missing_descriptions) > 0:

    print("WARNING: Missing descriptions:")
    print(
        missing_descriptions["concept_name"].tolist()
    )

else:

    print("All concepts have descriptions.")


# ============================================================
# SAVE CATALOG
# ============================================================

concepts.to_csv(
    OUTPUT_PATH,
    index=False
)


# ============================================================
# DISPLAY RESULTS
# ============================================================

print("\n" + "=" * 60)
print("SCHEMA CATALOG CREATED")
print("=" * 60)

print(f"Total concepts: {len(concepts)}")

print("\nConcepts by statement type:")

print(
    concepts["statement_type"]
    .value_counts()
)


print("\nOutput file:")
print(OUTPUT_PATH)


# ============================================================
# CLOSE DATABASE
# ============================================================

conn.close()